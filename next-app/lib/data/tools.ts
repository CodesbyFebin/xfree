export const INDEXABLE_TOOLS = TOOLS.filter((t) => t.indexable && t.status === 'published');

export const INDEXABLE_TOOL_SLUGS = new Set(INDEXABLE_TOOLS.map((t) => t.slug));

export function findToolBySlug(slug: string): ToolDefinition | undefined {
  return TOOLS.find((t) => t.slug === slug);
}

export function getRelatedTools(tool: ToolDefinition): ToolDefinition[] {
  return tool.relatedToolIds
    .map((id) => TOOLS.find((t) => t.id === id))
    .filter((t): t is ToolDefinition => t !== undefined);
}
